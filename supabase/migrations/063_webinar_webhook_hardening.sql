CREATE TABLE IF NOT EXISTS public.webinar_registrants (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  webinar_id UUID NOT NULL REFERENCES public.webinars(id) ON DELETE CASCADE,
  account_id UUID,
  name TEXT,
  phone TEXT NOT NULL,
  custom_data JSONB NOT NULL DEFAULT '{}'::jsonb,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (webinar_id, phone)
);

CREATE TABLE IF NOT EXISTS public.webinar_campaign_queue (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  webinar_id UUID NOT NULL REFERENCES public.webinars(id) ON DELETE CASCADE,
  registrant_id UUID NOT NULL REFERENCES public.webinar_registrants(id) ON DELETE CASCADE,
  trigger_type TEXT NOT NULL,
  scheduled_for TIMESTAMPTZ NOT NULL,
  status TEXT NOT NULL DEFAULT 'pending',
  sent_at TIMESTAMPTZ,
  error_message TEXT,
  processing_started_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS webinar_campaign_queue_due_idx
  ON public.webinar_campaign_queue(status, scheduled_for);

ALTER TABLE public.webinars
  ADD COLUMN IF NOT EXISTS webhook_secret_hash TEXT;

ALTER TABLE public.webinar_campaign_queue
  ADD COLUMN IF NOT EXISTS processing_started_at TIMESTAMPTZ;

DO $$
DECLARE
  constraint_row RECORD;
BEGIN
  FOR constraint_row IN
    SELECT conname
    FROM pg_constraint
    WHERE conrelid = 'public.webinar_campaign_queue'::regclass
      AND contype = 'c'
      AND pg_get_constraintdef(oid) ILIKE '%status%'
  LOOP
    EXECUTE format(
      'ALTER TABLE public.webinar_campaign_queue DROP CONSTRAINT %I',
      constraint_row.conname
    );
  END LOOP;

  ALTER TABLE public.webinar_campaign_queue
    ADD CONSTRAINT webinar_campaign_queue_status_check
    CHECK (status IN ('pending', 'processing', 'sent', 'failed'));
END $$;

CREATE TABLE IF NOT EXISTS public.webinar_webhook_rate_limits (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  webinar_id UUID NOT NULL REFERENCES public.webinars(id) ON DELETE CASCADE,
  requested_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS webinar_webhook_rate_limits_window_idx
  ON public.webinar_webhook_rate_limits(webinar_id, requested_at DESC);

