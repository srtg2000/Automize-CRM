CREATE OR REPLACE FUNCTION public.consume_webinar_webhook_rate_limit(
  p_webinar_id UUID,
  p_limit INTEGER DEFAULT 60
)
RETURNS BOOLEAN
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  recent_requests INTEGER;
BEGIN
  IF p_limit < 1 THEN
    RAISE EXCEPTION 'p_limit must be positive';
  END IF;

  PERFORM pg_advisory_xact_lock(hashtextextended(p_webinar_id::TEXT, 0));

  SELECT count(*)::INTEGER
  INTO recent_requests
  FROM public.webinar_webhook_rate_limits
  WHERE webinar_id = p_webinar_id
    AND requested_at > now() - INTERVAL '1 minute';

  IF recent_requests >= p_limit THEN
    RETURN FALSE;
  END IF;

  INSERT INTO public.webinar_webhook_rate_limits(webinar_id)
  VALUES (p_webinar_id);

  DELETE FROM public.webinar_webhook_rate_limits
  WHERE webinar_id = p_webinar_id
    AND requested_at <= now() - INTERVAL '1 minute';

  RETURN TRUE;
END;
$$;

CREATE OR REPLACE FUNCTION public.claim_due_webinar_campaigns(
  p_limit INTEGER DEFAULT 20
)
RETURNS TABLE(id UUID)
LANGUAGE sql
SECURITY DEFINER
SET search_path = public
AS $$
  WITH candidates AS (
    SELECT queue.id
    FROM public.webinar_campaign_queue AS queue
    WHERE (
      (queue.status = 'pending' AND queue.scheduled_for <= now())
      OR (
        queue.status = 'processing'
        AND queue.processing_started_at < now() - INTERVAL '15 minutes'
      )
    )
    ORDER BY queue.scheduled_for ASC
    LIMIT LEAST(GREATEST(COALESCE(p_limit, 20), 1), 100)
    FOR UPDATE SKIP LOCKED
  ),
  claimed AS (
    UPDATE public.webinar_campaign_queue AS queue
    SET status = 'processing',
        processing_started_at = now()
    FROM candidates
    WHERE queue.id = candidates.id
    RETURNING queue.id
  )
  SELECT claimed.id FROM claimed;
$$;

REVOKE ALL ON FUNCTION public.consume_webinar_webhook_rate_limit(UUID, INTEGER)
  FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.consume_webinar_webhook_rate_limit(UUID, INTEGER)
  TO service_role;

REVOKE ALL ON FUNCTION public.claim_due_webinar_campaigns(INTEGER)
  FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.claim_due_webinar_campaigns(INTEGER)
  TO service_role;
